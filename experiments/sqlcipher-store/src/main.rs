//! Runs the section 5 measurement matrix and prints/writes the results.
//! `cargo run --release` writes results/measurements.md and results/settings.txt.

use std::fmt::Write as _;
use std::fs;

use yap_sqlcipher_store::*;

const KEY: [u8; 32] = [0x42; 32];

fn main() {
    let work = scratch("report");
    let results = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("results");
    fs::create_dir_all(&results).unwrap();

    // Settings, read back from a live connection.
    let conn = open(&work.join("settings.db"), &KEY).unwrap();
    conn.execute_batch("CREATE TABLE t(x)").unwrap();
    let mut settings = String::new();
    for (k, v) in settings_report(&conn) {
        writeln!(settings, "{k} = {v}").unwrap();
    }
    drop(conn);
    fs::write(results.join("settings.txt"), &settings).unwrap();
    print!("{settings}");

    let configs = [
        ("cache_spill ON, cache_size -64 (64 KiB = 16 pages)", Config { cache_spill: true, cache_size_pages: Some(-64) }),
        ("cache_spill OFF, cache_size -64 (64 KiB = 16 pages)", Config { cache_spill: false, cache_size_pages: Some(-64) }),
        ("cache_spill ON, default cache_size (-2000)", Config { cache_spill: true, cache_size_pages: None }),
        ("cache_spill OFF, default cache_size (-2000)", Config { cache_spill: false, cache_size_pages: None }),
    ];
    let mut md = String::new();
    writeln!(md, "# Gate 1 measurements (generated by `cargo run --release`)\n").unwrap();
    writeln!(md, "Page size {PAGE}; frame = {FRAME_BYTES} bytes; estimate = 2 x pages(row maximum) summed + 16.").unwrap();
    writeln!(md, "`frames` is what the WAL hook reported after the commit (cross-checked against the log file length). `peak` is the largest total of database + log + wal-index + other files above the starting total, in pages, from samples after each statement (`s`) and with a 100 microsecond poller as well (`p`). Rolled-back transactions have no commit, so no frame count: only the peak is bounded.\n").unwrap();
    let mut all_pass = true;
    let mut fails = Vec::new();
    for (label, cfg) in configs {
        for variant in [Variant::Fresh, Variant::Used] {
            writeln!(md, "## {label}, {variant:?} database\n").unwrap();
            writeln!(md, "| operation | estimate | hook calls | frames (hook) | frames (file) | peak s / p | verdict |").unwrap();
            writeln!(md, "| --- | ---: | ---: | ---: | ---: | ---: | --- |").unwrap();
            for op in Op::ALL {
                let o = run_case(&work, &KEY, op, variant, cfg);
                let verdict = if o.pass() { "PASS" } else { "FAIL" };
                if !o.pass() {
                    all_pass = false;
                    fails.push(format!("{} / {label} / {variant:?}: {o:?}", op.label()));
                }
                let frames = if op.expects_commit() { o.frames_by_hook.to_string() } else { "n/a (no commit)".into() };
                let frames_f = if op.expects_commit() { o.frames_by_file.to_string() } else { format!("{} (log bytes {})", o.frames_by_file, o.peak_wal_bytes) };
                writeln!(md, "| {} | {} | {} | {} | {} | {} / {} | {} |", op.label(), o.estimate_pages, o.hook_calls, frames, frames_f, o.peak_extra_pages_sampled, o.peak_extra_pages_polled, verdict).unwrap();
            }
            writeln!(md).unwrap();
        }
    }
    let (fb, fa, fr) = incremental_vacuum_run(&work, &KEY);
    writeln!(md, "## Informational: `PRAGMA incremental_vacuum(256)` after deleting four large rows (no pass/fail rule)
").unwrap();
    writeln!(md, "Free pages before {fb}, after {fa}; frames appended by the vacuum step: {fr}.
").unwrap();
    writeln!(md, "**Overall: {}**", if all_pass { "every case within its estimate" } else { "SOME CASES EXCEEDED THE ESTIMATE" }).unwrap();
    for f in &fails {
        writeln!(md, "\n- {f}").unwrap();
    }
    fs::write(results.join("measurements.md"), &md).unwrap();
    print!("{md}");
}
